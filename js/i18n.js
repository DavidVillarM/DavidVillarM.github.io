window.I18n = {
  lang: "es",

  init() {
    this.lang = localStorage.getItem("lang") || document.documentElement.getAttribute("data-lang") || "es";
    this.apply(this.lang);
    const btn = document.getElementById("lang-toggle");
    btn?.addEventListener("click", () => {
      this.apply(this.lang === "es" ? "en" : "es");
    });
  },

  t(key) {
    return window.I18N[this.lang]?.[key] ?? window.I18N.es[key] ?? key;
  },

  apply(lang) {
    this.lang = lang;
    localStorage.setItem("lang", lang);
    document.documentElement.setAttribute("data-lang", lang);
    document.documentElement.lang = lang;

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      const val = this.t(key);
      if (el.hasAttribute("data-i18n-html")) el.innerHTML = val;
      else el.textContent = val;
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      el.setAttribute("placeholder", this.t(el.getAttribute("data-i18n-placeholder")));
    });

    document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      el.setAttribute("aria-label", this.t(el.getAttribute("data-i18n-aria")));
    });

    const metaDesc = document.querySelector('meta[name="description"]');
    const metaKey = document.body.getAttribute("data-meta-desc");
    if (metaDesc && metaKey) metaDesc.setAttribute("content", this.t(metaKey));

    const titleKey = document.body.getAttribute("data-meta-title");
    if (titleKey) document.title = this.t(titleKey);

    const langBtn = document.getElementById("lang-toggle");
    if (langBtn) langBtn.textContent = lang === "es" ? "EN" : "ES";

    const themeBtn = document.getElementById("theme-toggle");
    if (themeBtn) {
      const theme = document.documentElement.getAttribute("data-theme") || "dark";
      themeBtn.setAttribute("aria-label", this.t(theme === "dark" ? "theme.light" : "theme.dark"));
    }

    window.Projects?.renderAll?.();
  },
};
